def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _dump(path: Path, data: dict) -> None:
    # Сохраняем стабильный порядок: @@locale первым, затем ключи как в ru-шаблоне по возможности.
    text = json.dumps(data, ensure_ascii=False, indent=2)
    # trailing newline
    path.write_text(text + "\n", encoding="utf-8")


def _insert_keys(data: dict, additions: dict[str, object], after_key: str | None = None) -> dict:
    """Вставляет additions перед закрытием, сохраняя существующие значения."""
    out: dict = {}
    inserted = False
    for k, v in data.items():
        out[k] = v
        if after_key and k == after_key and not inserted:
            for ak, av in additions.items():
                if ak not in out:
                    out[ak] = av
            inserted = True
    for ak, av in additions.items():
        if ak not in out:
            out[ak] = av
    return out


def main() -> None:
    en_path = L10N / "app_en.arb"
    ru_path = L10N / "app_ru.arb"
    en = _load(en_path)
    ru = _load(ru_path)
    _fill_from_en_for_other_locales(en)

    # 1) Добавить NEW_KEYS во все локали.
    arb_files = sorted(L10N.glob("app_*.arb"))
    for path in arb_files:
        data = _load(path)
        locale = data.get("@@locale") or path.stem.split("_", 1)[-1]
        additions: dict[str, object] = {}
        for key, by_lang in NEW_KEYS.items():
            if key in data:
                continue
            additions[key] = by_lang.get(locale) or by_lang.get("en") or by_lang["ru"]
            # простые плейсхолдеры
            if "{place}" in str(additions[key]):
                additions[f"@{key}"] = {"placeholders": {"place": {"type": "int"}}}
            elif "{name}" in str(additions[key]) and key == "gameTurnOf":
                additions[f"@{key}"] = {"placeholders": {"name": {"type": "String"}}}
            elif "{count}" in str(additions[key]):
                additions[f"@{key}"] = {"placeholders": {"count": {"type": "int"}}}
        if additions:
            data = _insert_keys(data, additions)
            _dump(path, data)
            print(f"+ new keys → {path.name}: {len(additions)}")

    # 2) Синхронизировать 48 ключей из en во все не-en/ru.
    en = _load(en_path)  # reload after new keys
    for path in arb_files:
        data = _load(path)
        locale = data.get("@@locale") or path.stem.split("_", 1)[-1]
        if locale in ("en", "ru"):
            continue
        tr = LOCALE_TRANSLATIONS.get(locale, {})
        additions = {}
        for key in SYNC_FROM_EN:
            if key in data:
                continue
            additions[key] = tr.get(key) or en[key]
            meta_key = f"@{key}"
            if meta_key in en and meta_key not in data:
                additions[meta_key] = en[meta_key]
        if additions:
            # Вставить рядом с gamesTicTacToe если есть
            after = "gamesTicTacToe" if "gamesTicTacToe" in data else None
            data = _insert_keys(data, additions, after_key=after)
            _dump(path, data)
            print(f"+ sync → {path.name}: {len([k for k in additions if not k.startswith('@')])} keys")

    # Проверка
    en_keys = {k for k in _load(en_path) if not str(k).startswith("@") and k != "@@locale"}
    for path in sorted(L10N.glob("app_*.arb")):
        keys = {k for k in _load(path) if not str(k).startswith("@") and k != "@@locale"}
        missing = sorted(en_keys - keys)
        if missing:
            print(f"WARN {path.name} still missing {len(missing)}: {missing[:8]}")
        else:
            print(f"OK {path.name} ({len(keys)} keys)")


if __name__ == "__main__":
    main()
