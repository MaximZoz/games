#!/usr/bin/env python3
"""Generate client/lib/l10n/catalog_data.g.dart — shop/achievement titles by locale."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG_RU = Path(__file__).with_name("shop_catalog_ru.json")
OUT = ROOT / "client/lib/l10n/catalog_data.g.dart"

LANGS = [
    "ar", "be", "cs", "da", "de", "el", "en", "es", "fi", "fr", "he", "hi",
    "id", "it", "ja", "kk", "ko", "nb", "nl", "pl", "pt", "ru", "sv", "th",
    "tr", "uk", "uz", "vi", "zh",
]

# Load EN master + per-lang overlays from companion JSON (keeps this script shorter).
DATA = json.loads(Path(__file__).with_name("catalog_translations.json").read_text(encoding="utf-8"))


def dart_escape(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    catalog = json.loads(CATALOG_RU.read_text(encoding="utf-8"))
    en_titles: dict[str, str] = DATA["titles_en"]
    overlays: dict[str, dict[str, str]] = DATA["overlays"]
    achievements = DATA["achievements"]
    frame_desc = DATA["frame_descriptions"]
    flags = DATA["flags"]

    # Fill missing EN from code
    for code, meta in catalog.items():
        if code not in en_titles:
            if code.startswith("emoji_flag_"):
                iso = code.removeprefix("emoji_flag_")
                en_titles[code] = flags["en"].get(iso, iso.upper())
            elif code.startswith("stake_"):
                # stakes resolved by template in Dart
                en_titles[code] = meta["title_ru"]
            else:
                base = code
                for p in ("emoji_game_", "emoji_", "coll_", "pack_", "frame_"):
                    if base.startswith(p):
                        base = base[len(p) :]
                        break
                en_titles[code] = base.replace("_", " ").title()

    # locale -> code -> title
    by_locale: dict[str, dict[str, str]] = {lang: {} for lang in LANGS}
    for code, meta in catalog.items():
        ru = meta["title_ru"]
        en = en_titles[code]
        for lang in LANGS:
            if lang == "ru":
                by_locale[lang][code] = ru
            elif code.startswith("emoji_flag_"):
                iso = code.removeprefix("emoji_flag_")
                by_locale[lang][code] = flags.get(lang, {}).get(iso) or flags["en"].get(iso, en)
            elif code.startswith("stake_"):
                # keep empty — Dart templates
                continue
            else:
                by_locale[lang][code] = overlays.get(lang, {}).get(code) or overlays.get(lang, {}).get(en) or en

    # Achievements
    ach_titles: dict[str, dict[str, str]] = {}
    ach_descs: dict[str, dict[str, str]] = {}
    for code, block in achievements.items():
        ach_titles[code] = {lang: block["title"].get(lang, block["title"]["en"]) for lang in LANGS}
        ach_descs[code] = {
            lang: block["description"].get(lang, block["description"]["en"]) for lang in LANGS
        }

    frame_descs_out: dict[str, dict[str, str]] = {}
    for code, block in frame_desc.items():
        frame_descs_out[code] = {lang: block.get(lang, block["en"]) for lang in LANGS}

    def emit_map(name: str, data: dict[str, dict[str, str]]) -> str:
        lines = [f"const Map<String, Map<String, String>> {name} = {{"]
        for code in sorted(data):
            lines.append(f"  {dart_escape(code)}: {{")
            for lang in LANGS:
                if lang in data[code]:
                    lines.append(f"    {dart_escape(lang)}: {dart_escape(data[code][lang])},")
            lines.append("  },")
        lines.append("};")
        return "\n".join(lines)

    # Invert shop titles to code -> lang -> title for compact lookup matching achievements
    shop_by_code: dict[str, dict[str, str]] = {}
    for lang, mapping in by_locale.items():
        for code, title in mapping.items():
            shop_by_code.setdefault(code, {})[lang] = title

    parts = [
        "// GENERATED by tools/i18n/gen_catalog.py — do not edit by hand.",
        "// ignore_for_file: prefer_single_quotes",
        "",
        emit_map("kShopTitles", shop_by_code),
        "",
        emit_map("kAchievementTitles", ach_titles),
        "",
        emit_map("kAchievementDescriptions", ach_descs),
        "",
        emit_map("kFrameDescriptions", frame_descs_out),
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} shop={len(shop_by_code)} ach={len(ach_titles)}")


if __name__ == "__main__":
    main()
