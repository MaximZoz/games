def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _dump(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def build_locale_translations(en: dict) -> dict[str, dict[str, str]]:
    """Merge LOCALE_TRANSLATIONS (da + extras), RULES_TR, and PATCH."""
    _sync._fill_from_en_for_other_locales(en)
    locale_tr = _sync.LOCALE_TRANSLATIONS

    result: dict[str, dict[str, str]] = {}
    all_locales = sorted(
        {p.stem.split("_", 1)[-1] for p in L10N.glob("app_*.arb")} - SKIP_LOCALES
    )

    for loc in all_locales:
        merged: dict[str, str] = {}
        for key in SYNC_FROM_EN:
            if key in en:
                merged[key] = en[key]
        if loc in locale_tr:
            for key in SYNC_FROM_EN:
                if key in locale_tr[loc]:
                    merged[key] = locale_tr[loc][key]
        if loc in RULES_TR:
            merged.update(RULES_TR[loc])
        if loc in PATCH:
            merged.update(PATCH[loc])
        result[loc] = merged

    return result


def verify(en: dict, translations: dict[str, dict[str, str]]) -> dict[str, list[str]]:
    """Return keys still equal to EN per locale (excluding allowed same-as-EN)."""
    issues: dict[str, list[str]] = {}
    for path in sorted(L10N.glob("app_*.arb")):
        data = _load(path)
        locale = data.get("@@locale") or path.stem.split("_", 1)[-1]
        if locale in SKIP_LOCALES:
            continue
        same = []
        for key in SYNC_FROM_EN:
            if key not in data:
                continue
            if data[key] == en.get(key) and key not in ALLOW_SAME_AS_EN:
                same.append(key)
        if same:
            issues[locale] = same
    return issues


def main() -> int:
    en_path = L10N / "app_en.arb"
    en = _load(en_path)
    translations = build_locale_translations(en)

    updated_files = 0
    updated_keys = 0
    en_meta = {
        f"@{k}": en[f"@{k}"] for k in SYNC_FROM_EN if f"@{k}" in en
    }

    for path in sorted(L10N.glob("app_*.arb")):
        data = _load(path)
        locale = data.get("@@locale") or path.stem.split("_", 1)[-1]
        if locale in SKIP_LOCALES:
            print(f"-- skip {path.name}")
            continue

        tr = translations.get(locale, {})
        file_changes = 0
        for key in SYNC_FROM_EN:
            if key not in tr:
                print(f"WARN {path.name}: no translation for {key}")
                continue
            new_val = tr[key]
            if data.get(key) != new_val:
                data[key] = new_val
                file_changes += 1
            meta_key = f"@{key}"
            if meta_key in en_meta and meta_key not in data:
                data[meta_key] = en_meta[meta_key]
                file_changes += 1

        if file_changes:
            _dump(path, data)
            updated_files += 1
            updated_keys += file_changes
            print(f"OK {path.name}: {file_changes} updates")
        else:
            print(f"-- {path.name}: already up to date")

    print(f"\nSummary: {updated_files} files, {updated_keys} key updates")

    issues = verify(en, translations)
    if issues:
        print("\nKeys still equal to EN (unexpected):")
        for loc, keys in sorted(issues.items()):
            print(f"  {loc}: {keys}")
        return 1

    print("\nVerification: all non-en/ru/uk locales OK (no unexpected EN stubs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
